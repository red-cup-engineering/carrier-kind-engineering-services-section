import { fact } from "@red-cup-engineering/computer-system-engine/rpc/operation";
/**
 * acting/prompt — the composed-message class: a prompt is a cocone leg.
 *
 * A `prompt` injects a *composed message template* into the package's call
 * surface: a named, argument-taking recipe that renders MCP prompt messages. It
 * is the third standard MCP knowledge-vault primitive (alongside tools and
 * resources). `induceSurface` collects prompts into the one apex; the MCP transport
 * projects them as `prompts/list` and `prompts/get`.
 *
 * Prompts compose from what the package already declares. `actionPrompt` derives
 * one prompt from an action's own summary/description/codec metadata — so every
 * registered morphism is, for free, a guided prompt an agent can fill in and run.
 * A package may also register richer composed flows (e.g. a research flow that
 * chains several actions) by calling `prompt()` directly.
 */


/**
 * One rendered MCP prompt message.
 *
 * The current surface emits text-only user/assistant messages because the
 * package is projecting carrier/action context, not owning a chat runtime.
 */

/**
 * Declared argument for a prompt template.
 *
 * Arguments are descriptor data for clients and agents. The package does not
 * validate semantic completeness beyond carrying `required`; the prompt's
 * `compose` function decides how to use the supplied strings.
 */

/**
 * Registered composed-message template over an induced action family.
 *
 * A prompt is the guidance side of the action knowledge-vault surface: it turns
 * declared arguments into messages an MCP-capable client can show or send before
 * invoking an action. Prompts live in the same induced apex as tools and
 * resources; they are not a second agent-planning layer.
 */

/**
 * Input accepted by `prompt()`.
 *
 * Use this for custom package guidance that cannot be derived from one action
 * alone. Per-action prompts are usually generated by `actionPrompt`.
 */

/**
 * Pure prompt metadata, without the compose function.
 *
 * This is the shape projected to MCP `prompts/list`. Rendering prompt messages
 * is a separate `prompts/get` step.
 */

/**
 * Register a composed-message template as a prompt leg.
 *
 * The function validates the name and compose function, freezes the carrier,
 * and preserves the declared argument descriptors for discovery.
 */
export function prompt(spec) {
  if (!spec.name || spec.name.trim() === "") throw new TypeError("prompt: name is required");
  if (typeof spec.compose !== "function") throw new TypeError("prompt: compose must be a function");
  return Object.freeze({
    kind: "relating.prompt",
    name: spec.name,
    ...(spec.description === undefined ? {} : { description: spec.description }),
    arguments: Object.freeze([...(spec.arguments ?? [])]),
    compose: spec.compose,
  });
}

/**
 * Test whether a value is a prompt carrier.
 *
 * `collectPrompts` uses this guard when inducing a module namespace, so custom
 * prompts can be exported next to actions and resources.
 */
export function isPrompt(value) {
  return typeof value === "object" && value !== null && (value).kind === "relating.prompt";
}

/**
 * Build one text user message for a prompt result.
 */
export function userMessage(text) {
  return Object.freeze({ role: "user", content: Object.freeze({ type: "text", text }) });
}

/**
 * Project a prompt carrier to descriptor metadata.
 *
 * The descriptor contains no compose function, matching the discovery/list side
 * of MCP prompts.
 */
export function promptDescriptor(pr) {
  return Object.freeze({
    name: pr.name,
    ...(pr.description === undefined ? {} : { description: pr.description }),
    arguments: pr.arguments,
  });
}

/**
 * Derive a prompt from an action: a guided template that asks the agent to
 * produce the action's input carrier and run the verb. Composed entirely from
 * the action's own declared metadata — no second description.
 *
 * This is the package's small anti-drift move for agent-facing docs: the prompt
 * uses the action verb, summary, description, and wire codecs already declared
 * on the action, so tool guidance follows the carrier/action registry.
 */
export function actionPrompt(act) {
  const summary = act.summary ?? `the ${act.verb} morphism`;
  return prompt({
    name: act.verb,
    description: act.summary ?? act.description ?? `Invoke the ${act.verb} operation.`,
    arguments: [
      Object.freeze({ name: "input", description: `The ${act.inputFormat} input carrier for ${act.verb}.`, required: true }),
    ],
    compose: (args) => {
      const lines = [
        `Operation: ${act.verb} — ${summary}.`,
        ...(act.description === undefined ? [] : [act.description]),
        `Input wire: ${act.inputFormat}. Output wire: ${act.outputFormat}.`,
        "",
        `Produce a well-formed ${act.inputFormat} input carrier, then call ${act.verb} with it.`,
        ...(args["input"] === undefined || args["input"] === "" ? [] : ["", "Given input:", args["input"]]),
      ];
      return [userMessage(lines.join("\n"))];
    },
  });
}

/**
 * Project a prompt into package utterance facts.
 *
 * These facts let the induced discovery carrier describe prompt membership in
 * the same relational vocabulary as actions and resources.
 */
export function promptUtterances(pr) {
  const term = `relating.prompt.${pr.name}`;
  const facts = [fact(term, "relating.prompt.has-name", pr.name)];
  if (pr.description !== undefined) facts.push(fact(term, "relating.prompt.description", pr.description));
  for (const arg of pr.arguments) facts.push(fact(term, "relating.prompt.has-argument", arg.name));
  return Object.freeze(facts);
}
