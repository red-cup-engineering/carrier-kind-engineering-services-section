#!/usr/bin/env node
import { writeFileText } from "@red-cup-engineering/file-services/write-file";
import { runMain } from "@red-cup-engineering/javascript-file-services-section/javascript-file-main-guard";

import { bindingSpecifier } from "@red-cup-engineering/x402-services-section/compute-binding";

import { catalogForRuntime, compiledCatalogIdentities, compiledCatalogReadouts } from "../src/market.mjs";

/**
 * Compile the catalog: derive every offer's content identities on a Node
 * host and write data/records/catalog-identities.json, the record the edge
 * face loads so it derives nothing at request time. Run after every catalog
 * change; the app's test refuses a stale record.
 * It also writes data/records/catalog-readouts.json, the catalog readout and
 * agent card of each face on the production rails.
 * Usage: compile-catalog
 */
await runMain(async () => {
  const identities = new URL("../data/records/catalog-identities.json", import.meta.url).pathname;
  const readouts = new URL("../data/records/catalog-readouts.json", import.meta.url).pathname;
  const record = compiledCatalogIdentities();
  await writeFileText(identities, `${JSON.stringify(record, null, 2)}\n`);
  const faces = compiledCatalogReadouts();
  await writeFileText(readouts, `${JSON.stringify(faces, null, 2)}\n`);
  // The edge face's module map: a fetch-handler bundle resolves no specifier
  // at runtime, so every binding of every edge offer is imported statically
  // here and the face loads from this map instead of importing by name.
  const bindings = new URL("../src/edge-bindings.mjs", import.meta.url).pathname;
  const specifiers = [...new Set(catalogForRuntime("edge").flatMap((offer) => [offer.declaration.compute, offer.declaration.validate].filter(Boolean).map(bindingSpecifier)))].sort();
  const lines = [
    "// Generated by scripts/compile-catalog.mjs from data/records/catalog.json; do not hand-edit.",
    "// The edge face's static module map: every compute and validate binding of every",
    "// offer the edge serves, imported by name here because a fetch-handler bundle",
    "// resolves no specifier at runtime.",
    ...specifiers.map((specifier, index) => `import * as binding${index} from ${JSON.stringify(specifier)};`),
    "",
    "const EDGE_BINDINGS = new Map([",
    ...specifiers.map((specifier, index) => `  [${JSON.stringify(specifier)}, binding${index}],`),
    "]);",
    "",
    "/** Resolve one binding specifier from the compiled map; a specifier outside the edge catalog is refused. */",
    "export async function loadEdgeBinding(specifier) {",
    "  const module = EDGE_BINDINGS.get(specifier);",
    "  if (module === undefined) throw new TypeError(`edge face carries no module for ${specifier}; recompile the catalog`);",
    "  return module;",
    "}",
    "",
    "export const EDGE_BINDING_SPECIFIERS = Object.freeze([...EDGE_BINDINGS.keys()]);",
    "",
  ];
  await writeFileText(bindings, lines.join("\n"));
  return { identities, readouts, bindings, offers: Object.keys(record.identities).length, edgeOffers: faces.faces.edge.catalog.offers.length, edgeBindings: specifiers.length };
}, { moduleUrl: import.meta.url, formatResult: (result) => `${JSON.stringify(result)}\n` });
