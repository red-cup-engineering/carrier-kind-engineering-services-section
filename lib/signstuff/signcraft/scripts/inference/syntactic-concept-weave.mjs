// The predication Chu space of a toy language, as a weave (hand prototype of
// 2026-10-08; see the engineering note 2026-10-08-note-on-the-predication-chu-
// space-and-a-logical-inference-model.md, section 6). Run: RADIUS=1 node <this file>.
// points = substrings, states = contexts (l, r), r(w, (l,r)) in FOUR:
//   for-lane  : l w r is an attested sentence
//   against   : l w r is a refuted sentence
// FCA over the for-lane gives syntactic concepts (types); binary combination
// observed in the sample gives weave rules C -> C1 C2 (a Wang/bead matching
// rule; equivalently C1 <= C / C2 in the residuated lattice). A CYK weave over
// those rules judges unseen sentences in both lanes.
import { makeContext, intent, extent } from "@red-cup-engineering/metrologic/closure/formal-context";

const attested = [
  "the cat sleeps", "a dog runs", "the dog sleeps", "a cat runs",
  "the cat sees the dog", "a dog sees a cat", "the dog chases a cat",
  "a cat chases the dog", "the bird sings", "a bird sees the cat",
].map((s) => s.split(" "));
const refuted = ["cat the sleeps", "the sleeps cat", "a runs dog", "sees the cat dog"].map((s) => s.split(" "));

const key = (ws) => ws.join(" ");
const RADIUS = Number(process.env.RADIUS ?? 99); // light-cone radius of a context
const ctxKey = (l, r) => `${key(["<s>", ...l].slice(-RADIUS))}|${key([...r, "</s>"].slice(0, RADIUS))}`;

function splits(sentences) {
  const out = [];
  for (const s of sentences)
    for (let i = 0; i < s.length; i++)
      for (let j = i + 1; j <= s.length; j++)
        out.push([key(s.slice(i, j)), ctxKey(s.slice(0, i), s.slice(j))]);
  return out;
}
const pos = splits(attested), neg = splits(refuted);
const G = [...new Set(pos.map(([w]) => w))];
const M = [...new Set(pos.map(([, c]) => c))];
// metrologic's formal context, with the refuted lane as its denial lane
const negIn = neg.filter(([w, c]) => G.includes(w) && M.includes(c));
const ctx = makeContext(G, M, pos, negIn);

// a string's type: the concept it generates ({w}'' over the for-lane)
const posM = (B) => [...B].filter((m) => !String(m).startsWith("¬"));
const conceptOf = (w) => { const B = posM(intent(ctx, [w])); return { extent: extent(ctx, B), intent: B }; };
const cid = (c) => key([...c.extent].sort());

// The lattice: concepts generated by each string AND by each context (the
// context-generated ones are the large, generalizing types). A string's types
// are every concept whose extent holds it (Lambek: the up-set of its least type).
const concepts = new Map();
const addConcept = (B) => { const A = [...extent(ctx, B)]; if (!A.length) return null; const c = { extent: A.sort(), intent: posM(intent(ctx, A)) }; concepts.set(cid(c), c); return cid(c); };
for (const w of G) addConcept(posM(intent(ctx, [w])));
for (const m of M) addConcept([m]);
const typesOf = (w) => [...concepts.entries()].filter(([, c]) => c.extent.includes(w)).map(([id]) => id);
const Gset = new Set(G);
// residuated product restricted to the sample: C1∘C2 = (ext C1 · ext C2 ∩ G)''
const productMemo = new Map();
function product(id1, id2) {
  const k = id1 + "∘" + id2; if (productMemo.has(k)) return productMemo.get(k);
  const xs = []; for (const u of concepts.get(id1).extent) for (const v of concepts.get(id2).extent) { const uv = u + " " + v; if (Gset.has(uv)) xs.push(uv); }
  const out = xs.length ? addConcept(posM(intent(ctx, xs))) : null; productMemo.set(k, out); return out;
}
const SENT = `${key(["<s>"])}|${key(["</s>"])}`;
const isSentenceType = (id) => concepts.get(id).intent.includes(SENT);
const ruleList = [];

// CYK weave: chart cell (i, j) holds the bead colours (types) of span i..j;
// each bead's past light cone is its span; the matching rule is the product.
function weave(words) {
  const n = words.length, chart = [];
  for (let i = 0; i < n; i++) { chart[i] = []; chart[i][i + 1] = new Set(typesOf(words[i])); }
  for (let len = 2; len <= n; len++)
    for (let i = 0; i + len <= n; i++) {
      const j = i + len, cell = new Set();
      for (let k = i + 1; k < j; k++)
        for (const c1 of chart[i][k]) for (const c2 of chart[k][j]) { const c = product(c1, c2); if (c) cell.add(c); }
      chart[i][j] = cell;
    }
  return chart[0][n];
}
// FOUR reading of a whole sentence: for = weaves to S; against = refuted
// directly or contains a refuted substring in a refuted frame
function reading(sentence) {
  const ws = sentence.split(" ");
  const forLane = [...weave(ws)].some(isSentenceType);
  const againstLane = refuted.some((r) => key(r) === sentence);
  return ["neither", "true", "false", "both"][(forLane ? 1 : 0) + (againstLane ? 2 : 0)];
}

console.log(`radius=${RADIUS} |G| strings=${G.length} |M| contexts=${M.length} concepts=${concepts.size}`);
for (const c of concepts.values()) if (c.extent.length > 1 && c.extent.every((w) => !w.includes(" "))) console.log("  word type:", [...c.extent].join(" , "));
const probes = [
  "the bird runs", "a bird chases the cat", "the cat sees a bird", "the dog sees the bird", // unseen, grammatical
  "the bird sings", // attested
  "cat the sleeps", "sees the cat dog", // refuted
  "dog the a", "the the cat", // unseen, ungrammatical
];
for (const p of probes) console.log(`  ${reading(p).padEnd(8)} ${p}`);
